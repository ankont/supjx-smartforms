import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const files = ['plugin/media/js/form-adapter.js', 'plugin/media/js/smartbrowser-adapter.js', 'plugin/media/js/native-adapter.js', 'plugin/media/js/placement-engine.js', 'resources/js/bootstrap.js'];
const source = await Promise.all(files.map(file => readFile(resolve(root, file), 'utf8')));
const bundle = '// Generated by build/build-assets.mjs. Edit the adapter, engine or resources/js/bootstrap.js.\n'
  + '(() => {\n\'use strict\';\n'
  + source.map(text => text.replace(/^import .*;\r?\n/gm, '').replace(/^export class /gm, 'class ')).join('\n') + '\n})();\n';
await writeFile(resolve(root, 'plugin/media/js/smartforms.js'), bundle, 'utf8');
